import { test, expect } from '@playwright/test'

test('buttons keep the Figma geometry and block repeat activation while loading', async ({ page }) => {
  await page.goto('/design-system')
  const button = page.getByRole('button', { name: 'Simular espera' })
  await expect(button).toHaveCSS('height', '44px')
  await expect(button).toHaveCSS('background-color', 'rgb(23, 75, 63)')
  await button.hover()
  await expect(button).toHaveCSS('background-color', 'rgb(16, 47, 41)')
  await button.focus()
  await expect(button).toHaveCSS('outline-width', '2px')
  await button.click()
  await expect(button).toBeDisabled()
  await expect(button).toHaveAttribute('aria-busy', 'true')
  await page.keyboard.press('Enter')
  await expect(page.getByText('1 ativação. Durante a espera')).toBeVisible()
  await page.getByRole('button', { name: 'Finalizar espera' }).click()
  await expect(button).toBeEnabled()
  await button.click()
  await expect(page.getByText('2 ativações. Durante a espera')).toBeVisible()
})

test('fields expose labels, errors, read-only values and native selection', async ({ page }) => {
  await page.goto('/design-system#fields')
  const field = page.getByRole('textbox', { name: 'Setor vazio' })
  await field.fill('Expedição')
  await expect(field).toHaveValue('Expedição')
  await expect(field).toHaveAccessibleDescription('Informe o setor onde ocorreu o fato.')
  await expect(page.getByRole('textbox', { name: 'Setor com erro' })).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByRole('textbox', { name: 'Setor com erro' })).toHaveAccessibleDescription('Informe o setor para continuar.')
  await expect(page.getByRole('textbox', { name: 'Setor desabilitado' })).toBeDisabled()
  await expect(page.getByRole('textbox', { name: 'Setor em consulta' })).not.toBeEditable()
  await page.getByRole('combobox', { name: 'Selecionar setor', exact: true }).selectOption('Oficina de manutenção')
  await expect(page.getByRole('combobox', { name: 'Selecionar setor', exact: true })).toHaveValue('Oficina de manutenção')
})

test('checkboxes, radio groups and switches work with the keyboard', async ({ page }) => {
  await page.goto('/design-system#fields')
  const checkbox = page.getByRole('checkbox', { name: 'Selecionar EPI', exact: true })
  await checkbox.focus()
  await page.keyboard.press('Space')
  await expect(checkbox).toBeChecked()
  const group = page.getByRole('group', { name: 'Escolha única' })
  await group.getByRole('radio', { name: 'Incidente' }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(group.getByRole('radio', { name: 'Acidente' })).toBeChecked()
  await expect(group.getByRole('radio', { name: 'Incidente' })).not.toBeChecked()
  const toggle = page.getByRole('switch', { name: 'Mostrar somente pendências' })
  await toggle.focus()
  await page.keyboard.press('Space')
  await expect(toggle).toBeChecked()
  await expect(page.getByRole('switch', { name: 'Alternância indisponível' })).toBeDisabled()
})

test('form validation preserves data, focuses the error and announces the simulated result', async ({ page }) => {
  await page.goto('/design-system#form-example')
  const sector = page.getByRole('combobox', { name: 'Setor (obrigatório)' })
  const description = page.getByRole('textbox', { name: 'Descrição dos fatos (obrigatório)' })
  const submit = page.getByRole('button', { name: 'Testar envio' })
  await description.fill('Caixa próxima à passagem.')
  await submit.click()
  await expect(sector).toBeFocused()
  await expect(sector).toHaveAttribute('aria-invalid', 'true')
  await expect(description).toHaveValue('Caixa próxima à passagem.')
  await sector.selectOption('loading')
  await page.getByLabel('Anexos', { exact: true }).setInputFiles({ name: 'observacao.txt', mimeType: 'text/plain', buffer: Buffer.from('Fictional attachment.') })
  await submit.click()
  await expect(submit).toBeDisabled()
  await expect(page.getByText('Demonstração concluída. Nenhum registro foi enviado.')).toBeVisible()
  await expect(submit).toBeEnabled()
  await expect(sector).not.toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('button', { name: 'Limpar exemplo' }).click()
  await expect(description).toHaveValue('')
  await expect(sector).toHaveValue('')
})

test('confirmation contains focus, supports Escape and restores the opener', async ({ page }) => {
  await page.goto('/design-system#feedback')
  const opener = page.getByRole('button', { name: 'Testar confirmação de saída' })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: 'Descartar alterações?' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Continuar editando' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Descartar alterações', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: 'Continuar editando' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: 'Descartar alterações', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: 'Continuar editando' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(opener).toBeFocused()
  await opener.click()
  await dialog.getByRole('button', { name: 'Descartar alterações', exact: true }).click()
  await expect(page.getByText('Confirmação testada. Nenhum dado real foi alterado.')).toBeVisible()
  await page.getByRole('button', { name: 'Fechar aviso' }).click()
  await expect(page.getByText('Confirmação testada. Nenhum dado real foi alterado.')).not.toBeVisible()
})

