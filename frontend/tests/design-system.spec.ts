for (const width of [360, 768, 1344]) {
  test(`reference and catalog fit ${width}px with local fonts and working navigation`, async ({ page }, testInfo) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`) })
    await page.setViewportSize({ width, height: 960 })
    await page.goto('/design-system/examples/risk-areas')
    await page.evaluate(() => document.fonts.ready)
    await expect(page.getByRole('heading', { name: 'Áreas de risco', exact: true })).toHaveCSS('font-family', 'Manrope, sans-serif')
    const geometry = await page.getByRole('article').evaluateAll(cards => cards.map(card => ({ x: card.getBoundingClientRect().x, width: card.getBoundingClientRect().width, height: card.getBoundingClientRect().height })))
    expect(geometry[0].width).toBe(width === 1344 ? 520 : width === 768 ? 348 : 328)
    expect(geometry[0].height).toBeGreaterThanOrEqual(336)
    if (width === 360) expect(geometry[0].x).toBe(geometry[1].x)
    else expect(geometry[0].x).toBeLessThan(geometry[1].x)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`risk-areas-${width}.png`), fullPage: true })
    if (width < 1200) {
      const menu = page.getByRole('button', { name: 'Menu', exact: true })
      await menu.click()
      await expect(page.getByRole('dialog', { name: 'Navegação' })).toBeVisible()
      await page.keyboard.press('Escape')
      await expect(menu).toBeFocused()
      await menu.click()
      await page.setViewportSize({ width: 1344, height: 960 })
      await expect(page.getByRole('dialog', { name: 'Navegação' })).not.toBeVisible()
      await page.setViewportSize({ width, height: 960 })
    }
    await page.goto('/design-system')
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`catalog-${width}.png`), fullPage: true })
    expect(errors).toEqual([])
  })
}
